# Weekday pill in the widget: (font family, all caps). Mirrors DateStyles in DateStyle.kt.
PILL = {
    "classic": ("sans-serif-medium", False), "easy": ("sans-serif-medium", True),
    "giant": ("sans-serif-black", False), "contrast": ("sans-serif-medium", True),
    "night": ("sans-serif-light", False), "roman": ("serif", False),
    "d_classic": ("serif", True), "d_modern": ("sans-serif-medium", True),
    "d_minimal": ("sans-serif-light", False), "d_hacker": ("monospace", False),
    "d_punk": ("sans-serif-condensed", True), "d_neon": ("sans-serif-medium", True),
}


def pill_attrs(tid):
    font, caps = PILL[tid]
    return f'android:fontFamily="{font}"' + ('\n        android:textAllCaps="true"' if caps else "")


# Viewport 400 → center 200, face radius 0.96 * 200.
C = 200.0
R = 0.96 * C
HOUR = (0.52, 0.10, 0.085)   # length, tail, width — as fractions of R
MINUTE = (0.82, 0.10, 0.055)
SECOND = (0.88, 0.18, 0.02)
CAP = 0.06

# AnalogClock only scales drawables down, never up, so make them larger than any widget.
SIZE_DP = 600


def write(rel, text):
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def f(x):
    return f"{x:.1f}"


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)} a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0 a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0"


def vector(paths, size=f"{SIZE_DP}dp", viewport=400):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}"\n    android:height="{size}"\n'
        f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        + "".join(paths)
        + "</vector>\n"
    )


def stroke_path(d, color, width):
    return (
        f'    <path\n        android:pathData="{d}"\n        android:strokeColor="{color}"\n'
        f'        android:strokeLineCap="round"\n        android:strokeWidth="{f(width)}" />\n'
    )


def fill_path(d, color):
    return f'    <path\n        android:fillColor="{color}"\n        android:pathData="{d}" />\n'


def upright_hand(spec, color):
    length, tail, width = spec
    return stroke_path(f"M{f(C)},{f(C + tail * R)} L{f(C)},{f(C - length * R)}", color, width * R)


def hand_at(cx, cy, r, spec, deg, color):
    length, tail, width = spec
    a = math.radians(deg)
    sx, sy = cx - tail * r * math.sin(a), cy + tail * r * math.cos(a)
    ex, ey = cx + length * r * math.sin(a), cy - length * r * math.cos(a)
    return stroke_path(f"M{f(sx)},{f(sy)} L{f(ex)},{f(ey)}", color, width * r)


