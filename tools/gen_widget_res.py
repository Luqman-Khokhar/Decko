def day_bg(face, rim):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="{face}" />
    <stroke android:width="1dp" android:color="{rim}" />
    <corners android:radius="20dp" />
</shape>
'''


def mini_clock(cx, cy, r, face, rim, hour, minute, second):
    """Static 10:10:30 clock for preview/icon art."""
    paths = [fill_path(circle(cx, cy, r), face), stroke_path(circle(cx, cy, r * 0.98), rim, r * 0.022)]
    for i in range(12):
        a = math.radians(i * 30)
        w = 0.05 if i % 3 == 0 else 0.026
        x1, y1 = cx + r * 0.78 * math.sin(a), cy - r * 0.78 * math.cos(a)
        x2, y2 = cx + r * 0.90 * math.sin(a), cy - r * 0.90 * math.cos(a)
        paths.append(stroke_path(f"M{f(x1)},{f(y1)} L{f(x2)},{f(y2)}", rim, r * w))
    paths.append(hand_at(cx, cy, r, HOUR, 10 * 30 + 5, hour))
    paths.append(hand_at(cx, cy, r, MINUTE, 10 * 6 + 3, minute))
    paths.append(hand_at(cx, cy, r, SECOND, 30 * 6, second))
    paths.append(fill_path(circle(cx, cy, r * CAP), second))
    return paths


def main():
    for tid, (face, rim, hour, minute, second, text) in THEMES.items():
        cap = second or minute
        write(f"drawable/hand_hour_{tid}.xml", vector([upright_hand(HOUR, hour)]))
        minute_paths = [upright_hand(MINUTE, minute)]
        if not second:
            minute_paths.append(fill_path(circle(C, C, CAP * R), cap))
        write(f"drawable/hand_minute_{tid}.xml", vector(minute_paths))
        if second:
            write(f"drawable/hand_second_{tid}.xml",
                  vector([upright_hand(SECOND, second), fill_path(circle(C, C, CAP * R), cap)]))
        write(f"drawable/day_bg_{tid}.xml", day_bg(face, rim))
        write(f"layout/widget_clock_{tid}.xml", widget_layout(tid, bool(second), text))

    for tid, d in DIGITAL.items():
        write(f"drawable/day_bg_{tid}.xml", day_bg(d[0], d[1]))
        write(f"layout/widget_clock_{tid}.xml", digital_layout(tid, d))

    write("drawable/dial_transparent.xml", vector([fill_path(circle(C, C, 1), "#00000000")]))
    write("drawable/widget_preview.xml",
          vector(mini_clock(C, C, R, "#FAF9F6", "#2B2B2B", "#1F1F1F", "#1F1F1F", "#C8452C"), size="180dp"))
    # Adaptive icon: 108dp canvas, keep art inside the 66dp safe zone.
    write("drawable/ic_launcher_foreground.xml",
          vector(mini_clock(54, 54, 31, "#FAF9F6", "#2B2B2B", "#1F1F1F", "#1F1F1F", "#C8452C"),
                 size="108dp", viewport=108))


if __name__ == "__main__":
    main()
